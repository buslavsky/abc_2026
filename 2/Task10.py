# для введеных исходных данных является истинным, и значение False в противном случае.

# Функция для считывания целого числа от пользователя
def get_integer():
    while True:
        try:
            A = int(input("Введите целое число A: "))
            return A
        except ValueError:
            print("Пожалуйста, введите корректное целое число.")


# Функция для проверки четности числа
def is_even(A):
    return A % 2 == 0


# Функция для проверки нечетности числа
def is_odd(A):
    return A % 2 != 0


# Основная программа
def main():
    try:
        A = get_integer()

        # Проверка четности
        is_even_result = is_even(A)
        print(f"\nЧисло {A} является четным: {is_even_result}")

        # Проверка нечетности
        is_odd_result = is_odd(A)
        print(f"Число {A} является нечетным: {is_odd_result}")

    except ValueError as e:
        print(f"Произошла ошибка: {e}")


main()