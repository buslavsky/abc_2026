# В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов,
# обозначаемых названиями цвета: зеленый, красный, желтый, белый и черный.
# В каждом подцикле годы носят названия животных: крысы, коровы, тигра, зайца, дракона,
# змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи. По номеру года вывести его название,
# если 1984 год был началом цикла — годом зеленой крысы.

# Функция для определения названия года по его номеру, начиная с 1984 года
def get_year_name(year):
    # Определяем смещение относительно начала цикла
    start_year = 1984
    offset = (year - start_year) % 60

    # Список животных и цветов для 12-летнего цикла
    animals = ["крыса", "корова", "тигр", "заяц", "дракон", "змея",
               "лошадь", "овца", "обезьяна", "курица", "собака", "свинья"]
    colors = ["зелёный/зелёная", "красный/красная", "жёлтый/жёлтая", "белый/белая", "чёрный/чёрная"]

    # Вычисляем индекс животного и цвета
    animal_index = offset % 12
    color_index = ((offset % 10) //2)

    # Формируем название года
    year_name = f"{colors[color_index]} {animals[animal_index]}"
    return year_name


# Основная программа
def main():
    try:
        # Считываем год от пользователя
        year = int(input("Введите год (после 1984): "))

        # Проверяем, что год больше или равен 1984
        if year >= 1984:
            # Получаем и выводим название года
            name = get_year_name(year)
            print(f"\nГод {year} — это {name}")
        else:
            print("\nГод должен быть не меньше 1984.")
            main()  # Рекурсивный вызов для повторного ввода
    except ValueError:
        print("Пожалуйста, введите корректное числовое значение.")
        main()  # Рекурсивный вызов для повторного ввода


main()