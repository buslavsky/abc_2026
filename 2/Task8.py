# Функция для считывания четырехзначного числа от пользователя
def get_four_digit_number():
    while True:
        try:
            num = int(input("Введите четырехзначное число: "))
            if 1000 <= num <= 9999:
                return num
            else:
                print("Число должно быть четырехзначным (от 1000 до 9999).")
                get_four_digit_number()
        except ValueError:
            print("Пожалуйста, введите корректное числовое значение.")
            get_four_digit_number()


# Основная программа
def main():
    num = get_four_digit_number()

    # Разбиение числа на цифры
    a1 = num // 1000  # Первая цифра
    a2 = num // 100 % 10  # Вторая цифра
    a3 = num // 10 % 10  # Третья цифра
    a4 = num % 10  # Четвертая цифра

    # Проверка на палиндром
    if a1 == a4 and a2 == a3:
        print(f"\nЧисло {num} является палиндромом (читается одинаково слева направо и справа налево).")
    else:
        print(f"\nЧисло {num} не является палиндромом.")

main()