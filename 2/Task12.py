#  4 — тонна, 5 — центнер. Дан номер единицы массы и масса тела M в этих единицах (вещественное число).
#  Вывести массу данного тела в килограммах


# Функция для определения массы в килограммах по номеру единицы массы и значению массы
def convert_to_kilograms(unit_number, mass):
    if unit_number == 1:
        # Килограмм (1) остается без изменений
        return mass
    elif unit_number == 2:
        # Миллиграмм (2) — перевод в килограммы (1 мг = 10^-6 кг)
        return mass * 10 ** (-6)
    elif unit_number == 3:
        # Грамм (3) — перевод в килограммы (1 г = 10^-3 кг)
        return mass * 10 ** (-3)
    elif unit_number == 4:
        # Тонна (4) — перевод в килограммы (1 т = 1000 кг)
        return mass * 1000
    elif unit_number == 5:
        # Центнер (5) — перевод в килограммы (1 ц = 100 кг)
        return mass * 100
    else:
        return "Неправильно введен номер единицы массы"


# Основная программа
def main():
    try:
        # Считываем номер единицы массы
        unit_number = int(input("Введите номер единицы массы (1-5): "))

        # Проверяем, что номер находится в допустимом диапазоне
        if 1 <= unit_number <= 5:
            # Считываем массу в этой единице измерения
            mass = float(input("Введите массу в этой единице измерения: "))

            # Выводим результат перевода в килограммы
            result = convert_to_kilograms(unit_number, mass)
            print(
                f"\nМасса {mass} {['килограмм', 'миллиграмм', 'грамм', 'тонна', 'центнер'][unit_number - 1]} равна {result} килограммов")
        else:
            print("\nНеправильно введен номер единицы массы. Пожалуйста, выберите число от 1 до 5.")
            main()  # Рекурсивный вызов для повторного ввода
    except ValueError:
        print("Пожалуйста, введите корректные числовые значения.")
        main()  # Рекурсивный вызов для повторного ввода

main()